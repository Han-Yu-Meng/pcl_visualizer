/**
 * demo.js — synthetic room point cloud and PCD encoders.
 *
 * Powers the "加载示例" button and provides deterministic fixtures for the
 * parser tests (all three PCD encodings of the same cloud must agree).
 *
 * The synthetic room is deliberately slightly out of square so the
 * horizontal/vertical checks have something to find:
 *   floor  z = 0.010x - 0.006y        (~0.67 deg off level)
 *   wall   y = 6 - 0.018z             (~1.03 deg off plumb)
 */

function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Ground-truth tilt angles (degrees) of the demo room, for test assertions. */
export const DEMO_TRUTH = {
  floorAngle: Math.atan(Math.hypot(0.010, 0.006)) * 180 / Math.PI,
  wallAngle: Math.atan(0.018) * 180 / Math.PI,
};

export function createDemoCloud(seed = 20261104) {
  const rand = mulberry32(seed);
  const noise = (amp) => (rand() - 0.5) * 2 * amp;
  const xs = [], ys = [], zs = [], ins = [];
  const add = (x, y, z, i) => { xs.push(x); ys.push(y); zs.push(z); ins.push(i); };

  // Floor: slightly tilted, mostly planar with small sensor noise.
  for (let k = 0; k < 8000; k++) {
    const x = rand() * 8, y = rand() * 6;
    add(x, y, 0.010 * x - 0.006 * y + noise(0.0035), 0.18 + rand() * 0.10);
  }
  // Ceiling: flat.
  for (let k = 0; k < 2500; k++) {
    add(rand() * 8, rand() * 6, 3.0 + noise(0.0035), 0.42 + rand() * 0.08);
  }
  // Far wall (y = 6): leaning slightly inward with height.
  for (let k = 0; k < 3000; k++) {
    const x = rand() * 8, z = rand() * 3;
    add(x, 6 - 0.018 * z + noise(0.0035), z, 0.60 + rand() * 0.10);
  }
  // Near wall (y = 0): flat.
  for (let k = 0; k < 2500; k++) {
    add(rand() * 8, noise(0.0035), rand() * 3, 0.55 + rand() * 0.10);
  }
  // Right wall (x = 8) and left wall (x = 0): flat.
  for (let k = 0; k < 2500; k++) {
    add(8 + noise(0.0035), rand() * 6, rand() * 3, 0.70 + rand() * 0.08);
  }
  for (let k = 0; k < 2000; k++) {
    add(noise(0.0035), rand() * 6, rand() * 3, 0.50 + rand() * 0.08);
  }
  // A column and a low box, to make the scene less perfectly empty.
  for (let k = 0; k < 1500; k++) {
    const t = rand();
    if (t < 0.5) {
      const a = rand() * Math.PI * 2;
      add(4 + 0.18 * Math.cos(a), 3 + 0.18 * Math.sin(a), rand() * 3, 0.85);
    } else {
      const face = Math.floor(rand() * 5);
      if (face === 0) add(1 + rand() * 1.2, 1 + rand() * 1.2, 0.55 + noise(0.002), 0.80);
      else if (face === 1) add(1 + rand() * 1.2, 1 + noise(0.002), 0.2 + rand() * 0.35, 0.80);
      else if (face === 2) add(1 + noise(0.002), 1 + rand() * 1.2, 0.2 + rand() * 0.35, 0.80);
      else if (face === 3) add(2.2 + noise(0.002), 1 + rand() * 1.2, 0.2 + rand() * 0.35, 0.80);
      else add(1 + rand() * 1.2, 2.2 + noise(0.002), 0.2 + rand() * 0.35, 0.80);
    }
  }
  // Sparse stray points.
  for (let k = 0; k < 500; k++) {
    add(rand() * 8, rand() * 6, rand() * 3, rand());
  }

  const count = xs.length;
  const positions = new Float32Array(count * 3);
  const intensity = new Float32Array(count);
  for (let i = 0; i < count; i++) {
    positions[i * 3] = xs[i];
    positions[i * 3 + 1] = ys[i];
    positions[i * 3 + 2] = zs[i];
    intensity[i] = ins[i];
  }
  return { count, positions, intensity };
}

function headerText(n, encoding, rgb) {
  const fields = ['x', 'y', 'z', 'intensity'];
  const sizes = [4, 4, 4, 4];
  const types = ['F', 'F', 'F', 'F'];
  const counts = [1, 1, 1, 1];
  if (rgb) { fields.push('rgb'); sizes.push(4); types.push('U'); counts.push(1); }
  return [
    '# .PCD v0.7 - Point Cloud Data file format',
    '# generated by pcd_visualizer demo',
    'VERSION 0.7',
    'FIELDS ' + fields.join(' '),
    'SIZE ' + sizes.join(' '),
    'TYPE ' + types.join(' '),
    'COUNT ' + counts.join(' '),
    'WIDTH ' + n,
    'HEIGHT 1',
    'VIEWPOINT 0 0 0 1 0 0 0',
    'POINTS ' + n,
    'DATA ' + encoding,
    '',
  ].join('\n');
}

/** Valid (literal-run only) LZF stream — larger than the input, but standard. */
function lzfLiteralOnly(data) {
  const out = [];
  let i = 0;
  while (i < data.length) {
    const len = Math.min(32, data.length - i);
    out.push(len - 1);
    for (let j = 0; j < len; j++) out.push(data[i++]);
  }
  return Uint8Array.from(out);
}

function concat(headerStr, payloadBytes) {
  const h = new TextEncoder().encode(headerStr);
  const out = new Uint8Array(h.length + payloadBytes.length);
  out.set(h, 0);
  out.set(payloadBytes, h.length);
  return out.buffer;
}

/**
 * Encode the demo cloud as a PCD file.
 * @param {object} cloud result of createDemoCloud()
 * @param {'ascii'|'binary'|'binary_compressed'} encoding
 * @param {Uint32Array|null} rgb optional packed 0x00RRGGBB per point
 */
export function encodePCD(cloud, encoding = 'ascii', rgb = null) {
  const n = cloud.count;
  const stride = rgb ? 20 : 16;
  const header = headerText(n, encoding, !!rgb);

  if (encoding === 'ascii') {
    const lines = [];
    for (let i = 0; i < n; i++) {
      const row = [
        cloud.positions[i * 3].toFixed(6),
        cloud.positions[i * 3 + 1].toFixed(6),
        cloud.positions[i * 3 + 2].toFixed(6),
        cloud.intensity[i].toFixed(6),
      ];
      if (rgb) row.push(String(rgb[i] >>> 0));
      lines.push(row.join(' '));
    }
    return concat(header, new TextEncoder().encode(lines.join('\n') + '\n'));
  }

  if (encoding === 'binary') {
    const payload = new Uint8Array(n * stride);
    const dv = new DataView(payload.buffer);
    for (let i = 0; i < n; i++) {
      const o = i * stride;
      dv.setFloat32(o, cloud.positions[i * 3], true);
      dv.setFloat32(o + 4, cloud.positions[i * 3 + 1], true);
      dv.setFloat32(o + 8, cloud.positions[i * 3 + 2], true);
      dv.setFloat32(o + 12, cloud.intensity[i], true);
      if (rgb) dv.setUint32(o + 16, rgb[i] >>> 0, true);
    }
    return concat(header, payload);
  }

  if (encoding === 'binary_compressed') {
    // Structure-of-arrays layout used by PCL for compressed PCDs.
    const raw = new Uint8Array(n * stride);
    const dv = new DataView(raw.buffer);
    const block = [0, n * 4, n * 8, n * 12];
    if (rgb) block.push(n * 16);
    for (let i = 0; i < n; i++) {
      dv.setFloat32(block[0] + i * 4, cloud.positions[i * 3], true);
      dv.setFloat32(block[1] + i * 4, cloud.positions[i * 3 + 1], true);
      dv.setFloat32(block[2] + i * 4, cloud.positions[i * 3 + 2], true);
      dv.setFloat32(block[3] + i * 4, cloud.intensity[i], true);
      if (rgb) dv.setUint32(block[4] + i * 4, rgb[i] >>> 0, true);
    }
    const compressed = lzfLiteralOnly(raw);
    const payload = new Uint8Array(8 + compressed.length);
    const pdv = new DataView(payload.buffer);
    pdv.setUint32(0, compressed.length, true);
    pdv.setUint32(4, raw.length, true);
    payload.set(compressed, 8);
    return concat(header, payload);
  }

  throw new Error('unknown encoding: ' + encoding);
}

/** All encodings of the same cloud, plus a tiny colored sample. */
export function createSamplePCDs() {
  const cloud = createDemoCloud();
  const small = {
    count: 3,
    positions: new Float32Array([0, 0, 0, 1, 0, 0, 0, 1, 0]),
    intensity: new Float32Array([0.1, 0.5, 0.9]),
  };
  const smallRGB = new Uint32Array([0xff0000, 0x00ff00, 0x0000ff]);
  return {
    cloud,
    ascii: encodePCD(cloud, 'ascii'),
    binary: encodePCD(cloud, 'binary'),
    binary_compressed: encodePCD(cloud, 'binary_compressed'),
    rgbAscii: encodePCD(small, 'ascii', smallRGB),
    rgbBinary: encodePCD(small, 'binary', smallRGB),
    rgbCompressed: encodePCD(small, 'binary_compressed', smallRGB),
  };
}
